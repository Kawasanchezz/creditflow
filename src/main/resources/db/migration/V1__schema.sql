CREATE TABLE proposal (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id          BIGINT         NOT NULL,
    amount               NUMERIC(19, 2) NOT NULL CHECK (amount > 0),
    term                 INTEGER        NOT NULL CHECK (term > 0),
    rate                 NUMERIC(12, 8) NOT NULL CHECK (rate >= 0),
    system               VARCHAR(10)    NOT NULL CHECK (system IN ('PRICE', 'SAC')),
    status               VARCHAR(20)    NOT NULL,
    monthly_income       NUMERIC(19, 2) NOT NULL,
    existing_commitments NUMERIC(19, 2) NOT NULL,
    relationship_months  INTEGER        NOT NULL,
    valid_until          DATE,
    version              BIGINT         NOT NULL DEFAULT 0
);
CREATE INDEX idx_proposal_customer_status ON proposal (customer_id, status);

CREATE TABLE proposal_history (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proposal_id BIGINT      NOT NULL REFERENCES proposal (id),
    from_status VARCHAR(20),
    to_status   VARCHAR(20) NOT NULL,
    reason      VARCHAR(500),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_history_proposal_created ON proposal_history (proposal_id, created_at);

CREATE TABLE contract (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proposal_id     BIGINT       NOT NULL REFERENCES proposal (id),
    idempotency_key VARCHAR(100) NOT NULL,
    signed_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_contract_proposal UNIQUE (proposal_id),
    CONSTRAINT uq_contract_idempotency UNIQUE (idempotency_key)
);

CREATE TABLE installment (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_id BIGINT         NOT NULL REFERENCES contract (id),
    number      INTEGER        NOT NULL,
    due_date    DATE           NOT NULL,
    principal   NUMERIC(19, 2) NOT NULL,
    interest    NUMERIC(19, 2) NOT NULL,
    amount      NUMERIC(19, 2) NOT NULL,
    status      VARCHAR(15)    NOT NULL,
    paid_amount NUMERIC(19, 2),
    paid_at     TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_installment_number UNIQUE (contract_id, number)
);

CREATE TABLE credit_policy_result (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proposal_id BIGINT       NOT NULL REFERENCES proposal (id),
    rule_code   VARCHAR(50)  NOT NULL,
    outcome     VARCHAR(10)  NOT NULL,
    detail      VARCHAR(500)
);
CREATE INDEX idx_policy_result_proposal ON credit_policy_result (proposal_id);
