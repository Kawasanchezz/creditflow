ALTER TABLE credit_policy_result ADD COLUMN policy_version VARCHAR(40) NOT NULL DEFAULT 'legacy';

CREATE TABLE decision_outcome (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proposal_id BIGINT       NOT NULL REFERENCES proposal (id),
    type        VARCHAR(20)  NOT NULL CHECK (type IN ('CONTESTACAO', 'CHARGEBACK', 'INADIMPLENCIA', 'QUITACAO')),
    detail      VARCHAR(400),
    occurred_on DATE         NOT NULL,
    recorded_by VARCHAR(60)  NOT NULL,
    recorded_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_outcome_proposal ON decision_outcome (proposal_id, recorded_at);
